export function buildInitialBookings(): Booking[] {
  const normalized: Booking[] = mockBookings.map((booking) => ({
    orderType: booking.orderType ?? 'catering',
    ...booking,
  }));
  return normalized.map((booking) =>
    applyBookingValidation(booking, mockOperatorSettings, normalized)
  );
}

export function buildInitialInvoices(bookings: Booking[], menuItems: MenuItem[]) {
  return bookings
    .filter((b) => b.status === 'confirmed')
    .map((b) => generateInvoice(b, menuItems, mockPayments));
}
